# 2. 사용자 기준축으로 바꾸기


# ---------------------------
# 1. 데이터
# ---------------------------
coords = np.array([
    [0.6300804, 0.3862279, -0.1800956],
    [0.4410107, 0.3599773, -0.1550435],

    [0.5893860, 0.4558804, -0.3774264],
    [0.3353628, 0.4086872, -0.4049845],

    [0.5149344, 0.4169530, -0.7744084],
    [0.3939202, 0.3853071, -0.8478600],

    [0.5569154, 0.5336347, -0.0010835],  # left hip
    [0.4362963, 0.5337196, 0.0008508],   # right hip

    [0.6532460, 0.6436756, -0.0020700],
    [0.3949564, 0.6579794, -0.0496367],

    [0.7307456, 0.7352291, 0.4672561],
    [0.3446633, 0.7684151, 0.3005700],
])

EDGES = [
    (0,2), (2,4),
    (1,3), (3,5),
    (0,1),
    (6,7),
    (0,6), (1,7),
    (6,8), (8,10),
    (7,9), (9,11),
]

# ---------------------------
# 2. hip center 이동
# ---------------------------
lhip = coords[6]
rhip = coords[7]
hip_center = (lhip + rhip) / 2

coords_shifted = coords - hip_center

# ---------------------------
# 3. basis(기준축) 생성
# ---------------------------

# x축 (hip 방향)
x_axis = lhip - rhip
x_axis /= np.linalg.norm(x_axis)

# 방향 통일 (좌우 뒤집힘 방지)
if x_axis[0] < 0:
    x_axis = -x_axis

# y축 (몸 기준 → 위쪽 강제)
l_shoulder = coords[0]
r_shoulder = coords[1]
shoulder_center = (l_shoulder + r_shoulder) / 2

y_axis = shoulder_center - hip_center
y_axis /= np.linalg.norm(y_axis)

# 위쪽으로 강제
if y_axis[1] < 0:
    y_axis = -y_axis

# z축
z_axis = np.cross(x_axis, y_axis)
z_axis /= np.linalg.norm(z_axis)

# 앞뒤 방향 통일
if z_axis[2] < 0:
    z_axis = -z_axis

# 직교화
y_axis = np.cross(z_axis, x_axis)
y_axis /= np.linalg.norm(y_axis)

# 회전 행렬
R = np.stack([x_axis, y_axis, z_axis], axis=1)

# ---------------------------
# 4. basis 적용
# ---------------------------
coords_aligned = coords_shifted @ R

# ---------------------------
# 5. 시각화
# ---------------------------
fig = plt.figure(figsize=(18,6))

# -------- Original --------
ax1 = fig.add_subplot(131, projection='3d')
for i, j in EDGES:
    ax1.plot(
        [coords[i,0], coords[j,0]],
        [coords[i,2], coords[j,2]],
        [-coords[i,1], -coords[j,1]]
    )
ax1.scatter(coords[:,0], coords[:,2], -coords[:,1])
ax1.set_title("Original")

# -------- Hip Only --------
ax2 = fig.add_subplot(132, projection='3d')
for i, j in EDGES:
    ax2.plot(
        [coords_shifted[i,0], coords_shifted[j,0]],
        [coords_shifted[i,2], coords_shifted[j,2]],
        [-coords_shifted[i,1], -coords_shifted[j,1]]
    )
ax2.scatter(coords_shifted[:,0], coords_shifted[:,2], -coords_shifted[:,1])
ax2.set_title("Hip Center Only")

# -------- Basis --------
ax3 = fig.add_subplot(133, projection='3d')
for i, j in EDGES:
    ax3.plot(
        [coords_aligned[i,0], coords_aligned[j,0]],
        [coords_aligned[i,2], coords_aligned[j,2]],
        [-coords_aligned[i,1], -coords_aligned[j,1]]
    )
ax3.scatter(coords_aligned[:,0], coords_aligned[:,2], -coords_aligned[:,1])
