# 3. basis 생성 (안정화 버전)
# ---------------------------
# x축
x_axis = lhip - rhip
x_axis /= np.linalg.norm(x_axis)
if x_axis[0] < 0:
    x_axis = -x_axis

# y축 (몸 기준 → 위 방향 강제)
l_shoulder = coords[0]
