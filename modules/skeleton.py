# ---------------------------
# 5. 축 동일하게 맞추는 함수
# ---------------------------
def set_equal_axis(ax, data):
    x = data[:,0]
    y = data[:,2]
    z = -data[:,1]

    max_range = np.array([
        x.max()-x.min(),
        y.max()-y.min(),
        z.max()-z.min()
    ]).max() / 2.0

    mid_x = (x.max()+x.min()) / 2
    mid_y = (y.max()+y.min()) / 2
    mid_z = (z.max()+z.min()) / 2

    ax.set_xlim(mid_x - max_range, mid_x + max_range)
    ax.set_ylim(mid_y - max_range, mid_y + max_range)
    ax.set_zlim(mid_z - max_range, mid_z + max_range)

# ---------------------------
# 6. 시각화 함수
# ---------------------------
def draw(ax, data, title):
    for i, j in EDGES:
        ax.plot(
            [data[i,0], data[j,0]],
            [data[i,2], data[j,2]],
            [-data[i,1], -data[j,1]]
        )

    ax.scatter(
        data[:,0],
        data[:,2],
        -data[:,1]
    )

    # 원점 표시
    ax.scatter(0, 0, 0, color='red', s=100, label='origin')

    # 축 동일
    set_equal_axis(ax, data)
    ax.set_box_aspect([1,1,1])

    ax.set_title(title)
    ax.legend()

# ---------------------------
# 7. 실행
