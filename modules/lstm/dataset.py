import os
import glob

import numpy as np
import torch

from torch.utils.data import Dataset


class SwingDataset(Dataset):

    def __init__(self, folder_path):

        # 폴더 내 모든 npy 파일
        self.files = sorted(
            glob.glob(
                os.path.join(folder_path, "*.npy")
            )
        )

        print(f"총 데이터 개수: {len(self.files)}")

    # -----------------------------------

    def __len__(self):

        return len(self.files)

    # -----------------------------------

    def __getitem__(self, idx):

        # npy 파일 로드
        data = np.load(self.files[idx])

        # numpy -> tensor
        data = torch.tensor(
            data,
            dtype=torch.float32
        )

        return data